// probeScript reports which SAS 9.4 components exist under a configuration
// directory. It only tests for files; it changes nothing.
const probeScript = `d=%s
[ -d "$d" ] || { echo NOCONFIGDIR; exit 0; }
[ -x "$d/sas.servers" ] && echo SASSERVERS
[ -x "$d/SASMeta/MetadataServer/MetadataServer.sh" ] && echo METADATA
ls -d "$d"/Web/WebAppServer/SASServer* >/dev/null 2>&1 && echo WEBAPP
ls -d "$d"/ObjectSpawner >/dev/null 2>&1 && echo SPAWNER
ls -d "$d"/Applications/SASVisualAnalytics/HighPerformanceConfiguration >/dev/null 2>&1 && echo LASR
true`

type found struct {
	host  string
	flags map[string]bool
	err   string
}

// Discover inspects hosts and writes a draft configuration ordered
// metadata -> compute -> middle tier. Progress messages go to msg.
func Discover(ctx context.Context, w, msg io.Writer, hosts []string, user, configdir string, sshOpts []string) error {
	r := runner.New(sshOpts, true)
	var meta, compute, mid, skipped []found
	for _, h := range hosts {
		fmt.Fprintf(msg, "probing %s@%s ...\n", user, h)
		out := r.Run(ctx, user, h, fmt.Sprintf(probeScript, runner.ShellQuote(configdir)), 30*time.Second)
		f := found{host: h, flags: map[string]bool{}}
		if out.Err != nil {
			f.err = out.Err.Error()
		}
		for _, l := range strings.Fields(out.Output) {
			f.flags[l] = true
		}
		switch {
		case f.err != "" || f.flags["NOCONFIGDIR"] || (!f.flags["SASSERVERS"] && !f.flags["METADATA"]):
			skipped = append(skipped, f)
		case f.flags["METADATA"]:
			meta = append(meta, f)
		case f.flags["WEBAPP"]:
			mid = append(mid, f)
		default:
			compute = append(compute, f)
		}
	}
	if len(meta)+len(compute)+len(mid) == 0 {
		for _, f := range skipped {
			fmt.Fprintf(msg, "  %s: %s\n", f.host, skipReason(f))
		}
		return fmt.Errorf("no SAS components were found on any host; check --configdir, --user and SSH access (sas_lsm ssh-setup --hosts ...)")
	}
	hostsOf := func(fs []found) []string {
		var o []string
		for _, f := range fs {
			o = append(o, f.host)
		}
		return o
	}

	y := &yamlWriter{}
	y.comment("Draft generated by 'sas_lsm discover' on " + time.Now().Format("2006-01-02 15:04"))
	y.comment("Discovery checks which SAS components exist under " + configdir + " on each host.")
	y.comment("REVIEW the tier order and names before use, then run 'sas_lsm validate' and 'sas_lsm doctor'.")
	y.kv(0, "version", "1")
	y.blank()
	y.key(0, "settings")
	y.kv(2, "status_root", "/var/tmp/sas_lsm")
	y.comment("  admin_email: [sasadmin@example.com]")
	y.blank()
	y.key(0, "defaults")
	y.kv(2, "user", user)
	y.kv(2, "configdir", configdir)
	y.blank()
	y.key(0, "tiers")

	switch {
	case len(meta) >= 3:
		y.item(2, "name", "metadata")
		y.kv(4, "type", "metadata-cluster")
		y.list(4, "hosts", hostsOf(meta))
		for _, f := range meta {
			if f.flags["SPAWNER"] || f.flags["WEBAPP"] {
				y.comment(fmt.Sprintf("    NOTE: %s also hosts other servers; add a sas-servers tier for it if needed", f.host))
			}
		}
		y.blank()
	case len(meta) > 0:
		for i, f := range meta {
			name := "metadata"
			if len(meta) > 1 {
				name = fmt.Sprintf("metadata%d", i+1)
			}
			y.item(2, "name", name)
			y.kv(4, "type", "sas-servers")
			y.list(4, "hosts", []string{f.host})
			y.blank()
		}
		if len(meta) == 2 {
			y.comment("  NOTE: two metadata hosts were found; a SAS metadata cluster needs 3+ nodes. Check this layout.")
		}
	}
	if len(compute) > 0 {
		y.item(2, "name", "compute")
		y.kv(4, "type", "sas-servers")
		y.list(4, "hosts", hostsOf(compute))
		if len(compute) > 1 {
			y.kv(4, "parallel", "true")
		}
		for _, f := range compute {
			if f.flags["LASR"] {
				y.comment(fmt.Sprintf("    NOTE: %s has LASR configuration; LASR servers usually need a separate custom tier", f.host))
			}
		}
		y.blank()
	}
	if len(mid) > 0 {
		y.item(2, "name", "midtier")
		y.kv(4, "type", "sas-servers")
		y.list(4, "hosts", hostsOf(mid))
		y.kv(4, "retries", "30")
		if len(mid) > 1 {
			y.comment("    NOTE: several middle-tier hosts found. If they are a cluster, keep parallel: false.")
		}
		y.blank()
	}
	for _, f := range skipped {
		y.comment(fmt.Sprintf("SKIPPED %s - %s", f.host, skipReason(f)))
	}
	_, err := io.WriteString(w, y.String())
	return err
}

func skipReason(f found) string {
	switch {
	case f.err != "":
		return "could not connect: " + f.err
	case f.flags["NOCONFIGDIR"]:
		return "configdir does not exist on this host"
	}
	return "no sas.servers under configdir"
}
